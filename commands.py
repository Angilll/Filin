import os
import shutil
import history
from notes_gui import (
    VAULT,
    список_всех_папок,
    создать_папку_функция,
    перенести_файл_функция,
    перенести_папку_функция,
)

import ollama

МОДЕЛЬ_ИИ = "qwen2.5:7b"
ТРИГГЕР = "филин"
ПРОВЕРЯТЬ_СЛОВ = 3


# === УТИЛИТЫ ===

def безопасное_имя(текст):
    return "".join(c for c in текст if c not in '\\/:*?"<>|').strip()


def _путь(относительный):
    return os.path.join(VAULT, относительный.replace("/", os.sep))


def _есть_файл(относительный_путь):
    return os.path.isfile(_путь(относительный_путь))


def _найти_файл_по_имени(имя, расширения):
    """Ищет файл по имени без расширения во всём дереве.
    Возвращает относительный путь или None."""
    имя_нижн = имя.lower().strip()
    for корень, подпапки, файлы in os.walk(VAULT):
        подпапки[:] = [п for п in подпапки if not п.startswith(".")]
        for ф in файлы:
            базовое, расш = os.path.splitext(ф)
            if расш.lower() in расширения and базовое.lower() == имя_нижн:
                полный = os.path.join(корень, ф)
                return os.path.relpath(полный, VAULT).replace(os.sep, "/")
    return None


def _найти_папку_по_имени(имя):
    имя_нижн = имя.lower().strip()
    for корень, подпапки, файлы in os.walk(VAULT):
        подпапки[:] = [п for п in подпапки if not п.startswith(".")]
        for п in подпапки:
            if п.lower() == имя_нижн:
                полный = os.path.join(корень, п)
                return os.path.relpath(полный, VAULT).replace(os.sep, "/")
    return None


# === ТРИГГЕР ===

def найти_триггер(текст):
    """Проверяет первые ПРОВЕРЯТЬ_СЛОВ слов на 'Филин'.
    Возвращает текст после триггера или None."""
    слова = текст.split()
    for i in range(min(ПРОВЕРЯТЬ_СЛОВ, len(слова))):
        очищенное = слова[i].lower().strip(".,!?:;-—–\"'«»")
        if очищенное == ТРИГГЕР:
            остаток = " ".join(слова[i + 1:]).strip()
            # Убираем ведущие знаки препинания
            while остаток and остаток[0] in ".,!?:;-—–":
                остаток = остаток[1:].strip()
            return остаток
    return None


def извлечь_команды(текст):
    """Разбивает текст на команды по повторяющемуся 'Филин'.
    Возвращает список строк (без самого слова 'Филин')."""
    слова = текст.split()
    команды = []
    текущая = []
    найдено = False

    for слово in слова:
        очищенное = слово.lower().strip(".,!?:;-—–\"'«»")
        if очищенное == ТРИГГЕР:
            if найдено and текущая:
                команды.append(" ".join(текущая).strip())
            текущая = []
            найдено = True
        elif найдено:
            текущая.append(слово)

    if найдено and текущая:
        команды.append(" ".join(текущая).strip())

    # Чистим знаки препинания в конце каждой команды
    очищенные = []
    for к in команды:
        к = к.rstrip(".,!?:;-—–\"'«»").strip()
        if к:
            очищенные.append(к)
    return очищенные


# === РАЗБОР ОДНОЙ КОМАНДЫ ===

def _разбить_по_маркеру(текст, маркер):
    """Ищет маркер (например ' в ' или ' текст ') в тексте и режет по нему.
    Возвращает (до, после) или (текст, None), если маркера нет.
    Ищет маркер как отдельное слово."""
    нижний = текст.lower()
    индекс = нижний.find(маркер)
    if индекс == -1:
        return текст.strip(), None
    до = текст[:индекс].strip()
    после = текст[индекс + len(маркер):].strip()
    return до, после


def выполнить_команду(команда):
    """Выполняет одну команду.
    Возвращает (успех: bool, описание: str, выполнение_действия: bool).
    Третий параметр: True — если это была команда, False — если не распознали."""
    к = команда.lower().strip()
    оригинал = команда.strip()

    # --- СОЗДАЙ ПАПКУ ---
    if к.startswith("создай папку"):
        название = оригинал[len("создай папку"):].strip()
        if not название:
            return False, "не указано название папки", True
        ok, сообщение = создать_папку_функция(безопасное_имя(название))
        if ok:
            history.записать_действие(f"создана папка: {название}")
        return ok, сообщение, True

    # --- СОЗДАЙ ПОДПАПКУ ---
    if к.startswith("создай подпапку"):
        остаток = оригинал[len("создай подпапку"):].strip()
        название, место = _разбить_по_маркеру(остаток, " в ")
        if not название or not место:
            return False, "нужно: создай подпапку <название> в <место>", True
        относительный = f"{место}/{название}"
        ok, сообщение = создать_папку_функция(безопасное_имя(относительный).replace("\\", "/"))
        if ok:
            history.записать_действие(f"создана подпапка: {название} в {место}")
        return ok, сообщение, True

    # --- СОЗДАЙ ЗАМЕТКУ ---
    if к.startswith("создай заметку"):
        название = оригинал[len("создай заметку"):].strip()
        if not название:
            return False, "не указано название заметки", True
        папка_вх = _путь("Входящие")
        os.makedirs(папка_вх, exist_ok=True)
        имя_файла = безопасное_имя(название) + ".md"
        путь = os.path.join(папка_вх, имя_файла)
        счётчик = 1
        while os.path.exists(путь):
            имя_файла = f"{безопасное_имя(название)} ({счётчик}).md"
            путь = os.path.join(папка_вх, имя_файла)
            счётчик += 1
        with open(путь, "w", encoding="utf-8") as f:
            f.write(f"# {название}\n\n")
        history.записать_действие(f"создана заметка: {название}")
        return True, f"заметка создана: {название}", True

    # --- ЗАПИШИ В ЗАМЕТКУ ---
    if к.startswith("запиши в заметку"):
        остаток = оригинал[len("запиши в заметку"):].strip()
        название, текст = _разбить_по_маркеру(остаток, " текст ")
        if not название:
            return False, "нужно: запиши в заметку <название> текст <текст>", True
        if not текст:
            return False, "не указан текст для записи", True

        относительный = _найти_файл_по_имени(название, {".md"})
        if относительный is None:
            # Создаём новую заметку во Входящих
            папка_вх = _путь("Входящие")
            os.makedirs(папка_вх, exist_ok=True)
            имя_файла = безопасное_имя(название) + ".md"
            путь = os.path.join(папка_вх, имя_файла)
            with open(путь, "w", encoding="utf-8") as f:
                f.write(f"# {название}\n\n{текст}\n")
            history.записать_действие(f"создана заметка: {название} (с текстом)")
            return True, f"заметка создана: {название}", True

        путь = _путь(относительный)
        try:
            with open(путь, "a", encoding="utf-8") as f:
                f.write(f"\n{текст}\n")
            history.записать_действие(f"дописано в заметку: {название}")
            return True, f"дописано в заметку: {название}", True
        except Exception as e:
            return False, f"ошибка записи: {e}", True

    # --- ЗАПИШИ ТЕКСТ (без названия — ИИ придумывает) ---
    if к.startswith("запиши текст"):
        текст = оригинал[len("запиши текст"):].strip()
        if not текст:
            return False, "не указан текст", True
        промт = f"""Придумай короткое название (3–7 слов) для заметки со следующим текстом:
\"\"\"
{текст}
\"\"\"
Ответь СТРОГО одной строкой — только название, без кавычек и пояснений."""
        try:
            ответ = ollama.chat(model=МОДЕЛЬ_ИИ,
                                messages=[{"role": "user", "content": промт}])
            название = безопасное_имя(ответ["message"]["content"].strip().strip('"').strip("«»"))
        except Exception as e:
            return False, f"ошибка ИИ: {e}", True
        if not название:
            название = "Без названия"

        папка_вх = _путь("Входящие")
        os.makedirs(папка_вх, exist_ok=True)
        имя_файла = название + ".md"
        путь = os.path.join(папка_вх, имя_файла)
        счётчик = 1
        while os.path.exists(путь):
            имя_файла = f"{название} ({счётчик}).md"
            путь = os.path.join(папка_вх, имя_файла)
            счётчик += 1
        with open(путь, "w", encoding="utf-8") as f:
            f.write(f"# {название}\n\n{текст}\n")
        history.записать_действие(f"создана заметка: {название}")
        return True, f"заметка создана: {название}", True

    # --- ПЕРЕМЕСТИ ПАПКУ ---
    if к.startswith("перемести папку"):
        остаток = оригинал[len("перемести папку"):].strip()
        название, место = _разбить_по_маркеру(остаток, " в ")
        if not название or not место:
            return False, "нужно: перемести папку <название> в <место>", True
        относительный = _найти_папку_по_имени(название)
        if относительный is None:
            return False, f"папка не найдена: {название}", True
        ok, сообщение = перенести_папку_функция(относительный, место)
        if ok:
            history.записать_действие(f"перемещена папка: {название} в {место}")
        return ok, сообщение, True

    # --- ПЕРЕМЕСТИ ЗАМЕТКУ ---
    if к.startswith("перемести заметку"):
        остаток = оригинал[len("перемести заметку"):].strip()
        название, место = _разбить_по_маркеру(остаток, " в ")
        if not название or not место:
            return False, "нужно: перемести заметку <название> в <место>", True
        относительный = _найти_файл_по_имени(название, {".md"})
        if относительный is None:
            return False, f"заметка не найдена: {название}", True
        ok, сообщение = перенести_файл_функция(относительный, место)
        if ok:
            history.записать_действие(f"перемещена заметка: {название} в {место}")
        return ok, сообщение, True

    # --- ПЕРЕИМЕНУЙ ПАПКУ / ЗАМЕТКУ / АУДИО ---
    if к.startswith("переименуй"):
        остаток = оригинал[len("переименуй"):].strip()
        к_ост = остаток.lower()

        тип = None
        if к_ост.startswith("папку"):
            тип = "папка"
            остаток = остаток[len("папку"):].strip()
        elif к_ост.startswith("заметку"):
            тип = "заметка"
            остаток = остаток[len("заметку"):].strip()
        elif к_ост.startswith("аудио"):
            тип = "аудио"
            остаток = остаток[len("аудио"):].strip()

        if тип is None:
            return False, "нужно: переименуй папку/заметку/аудио <старое> в <новое>", True

        старое, новое = _разбить_по_маркеру(остаток, " в ")
        if not старое or not новое:
            return False, f"нужно: переименуй {тип} <старое> в <новое>", True

        новое_безопасное = безопасное_имя(новое)

        if тип == "папка":
            относительный = _найти_папку_по_имени(старое)
            if относительный is None:
                return False, f"папка не найдена: {старое}", True
            старый_путь = _путь(относительный)
            родитель = os.path.dirname(старый_путь)
            новый_путь = os.path.join(родитель, новое_безопасное)
            if os.path.exists(новый_путь):
                return False, f"папка {новое} уже существует", True
            try:
                os.rename(старый_путь, новый_путь)
                history.записать_действие(f"переименована папка: {старое} → {новое}")
                return True, f"папка переименована в {новое}", True
            except Exception as e:
                return False, f"ошибка: {e}", True

        if тип in {"заметка", "аудио"}:
            if тип == "заметка":
                расширения = {".md"}
                расширение_новое = ".md"
            else:
                расширения = {".mp3", ".wav", ".m4a", ".ogg", ".flac", ".opus", ".aac"}
                расширение_новое = None

            относительный = _найти_файл_по_имени(старое, расширения)
            if относительный is None:
                return False, f"{тип} не найдено: {старое}", True
            старый_путь = _путь(относительный)
            if расширение_новое is None:
                расширение_новое = os.path.splitext(старый_путь)[1]
            родитель = os.path.dirname(старый_путь)
            новый_путь = os.path.join(родитель, новое_безопасное + расширение_новое)
            if os.path.exists(новый_путь):
                return False, f"{тип} {новое} уже существует", True
            try:
                os.rename(старый_путь, новый_путь)
                history.записать_действие(f"переименовано {тип}: {старое} → {новое}")
                return True, f"{тип} переименовано в {новое}", True
            except Exception as e:
                return False, f"ошибка: {e}", True

    # --- РАСШИФРУЙ АУДИО ---
    if к.startswith("расшифруй аудио"):
        название = оригинал[len("расшифруй аудио"):].strip()
        if not название:
            return False, "укажи название аудио", True
        относительный = _найти_файл_по_имени(
            название,
            {".mp3", ".wav", ".m4a", ".ogg", ".flac", ".opus", ".aac"}
        )
        if относительный is None:
            return False, f"аудио не найдено: {название}", True
        # Расшифровка через Whisper будет вызвана из notes_gui,
        # здесь просто возвращаем путь и просьбу расшифровать.
        return True, f"__РАСШИФРОВАТЬ__:{относительный}", True

    # --- ОПИШИ ПАПКУ ---
    if к.startswith("опиши папку"):
        остаток = оригинал[len("опиши папку"):].strip()
        название, текст = _разбить_по_маркеру(остаток, " текст ")
        if not название or not текст:
            return False, "нужно: опиши папку <название> текст <описание>", True
        относительный = _найти_папку_по_имени(название)
        if относительный is None:
            return False, f"папка не найдена: {название}", True
        папка = _путь(относительный)
        имя_файла = безопасное_имя(текст) + ".txt"
        путь = os.path.join(папка, имя_файла)
        try:
            with open(путь, "w", encoding="utf-8") as f:
                f.write("")
            history.записать_действие(f"добавлено описание папки {название}: {текст}")
            return True, f"описание добавлено: {имя_файла}", True
        except Exception as e:
            return False, f"ошибка: {e}", True

    # --- НЕ РАСПОЗНАНО ---
    return False, f"не распознано: {команда}", False


def обработать_текст(текст):
    """Главная точка входа.
    Возвращает список кортежей (успех, описание, была_ли_команда)."""
    команды = извлечь_команды(текст)
    if not команды:
        return []

    history.записать_прочее(f"услышано: {текст}")

    результаты = []
    for команда in команды:
        try:
            ok, описание, была_команда = выполнить_команду(команда)
        except Exception as e:
            ok, описание, была_команда = False, f"ошибка: {e}", True

        результаты.append((ok, описание, была_команда))
        if not ok:
            history.записать_прочее(f"ошибка команды: {описание}")
    return результаты