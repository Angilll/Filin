import os
import json
from datetime import datetime

DATA_DIR = r"C:\Users\1\Desktop\Tot\Ai\data"
ФАЙЛ_ДЕЙСТВИЙ = os.path.join(DATA_DIR, "history_actions.json")
ФАЙЛ_ПРОЧЕГО = os.path.join(DATA_DIR, "history_other.json")

МАКСИМУМ_ЗАПИСЕЙ = 1000

def _загрузить(путь):
    if not os.path.isfile(путь):
        return []
    try:
        with open(путь, "r", encoding="utf-8") as f:
            данные = json.load(f)
        if isinstance(данные, list):
            return данные
        return []
    except Exception:
        return []

def _сохранить(путь, данные):
    os.makedirs(DATA_DIR, exist_ok=True)
    # Обрезаем до МАКСИМУМ_ЗАПИСЕЙ, оставляя самые свежие
    if len(данные) > МАКСИМУМ_ЗАПИСЕЙ:
        данные = данные[-МАКСИМУМ_ЗАПИСЕЙ:]
    with open(путь, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=2)

def _добавить(путь, текст):
    данные = _загрузить(путь)
    запись = {
        "время": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "текст": текст.strip()
    }
    данные.append(запись)
    _сохранить(путь, данные)

def записать_действие(текст):
    """Записывает в историю действий ИИ.
    Пример: записать_действие('создана папка Тесты')"""
    _добавить(ФАЙЛ_ДЕЙСТВИЙ, текст)

def записать_прочее(текст):
    """Записывает в общую историю: услышанное, ошибки, прочее.
    Пример: записать_прочее('услышано: Филин создай папку Тесты')"""
    _добавить(ФАЙЛ_ПРОЧЕГО, текст)

def прочитать_действия(последних=50):
    """Возвращает последние записи истории действий.
    Свежие — в начале списка."""
    данные = _загрузить(ФАЙЛ_ДЕЙСТВИЙ)
    return list(reversed(данные[-последних:]))

def прочитать_прочее(последних=50):
    данные = _загрузить(ФАЙЛ_ПРОЧЕГО)
    return list(reversed(данные[-последних:]))

def очистить_действия():
    _сохранить(ФАЙЛ_ДЕЙСТВИЙ, [])

def очистить_прочее():
    _сохранить(ФАЙЛ_ПРОЧЕГО, [])